import { describe, expect, it } from 'vitest';
import { normalize } from '../src/index';

describe('normalize', () => {
  const cases: [string, string][] = [
    ['1파티', '1파티'],
    ['1팟', '1파티'],
    ['일팟', '1파티'],
    ['일 파티', '1파티'],
    ['이파티', '2파티'],
    ['이 파티 너무 약하다', '이 파티 너무 약하다'],
    ['이번 파티 모여', '이번 파티 모여'],
    ['1 파티', '1파티'],
    ['1번 파티', '1파티'],
    ['십이파티', '12파티'],
    ['열두 파티', '12파티'],
    ['첫 파티', '1파티'],
    ['두 파티', '2파티'],
    ['1,2파티', '1파티 2파티'],
    ['1·2파티', '1파티 2파티'],
    ['1 2 파티', '1파티 2파티'],
    ['1, 2, 3파티', '1파티 2파티 3파티'],
    ['1과 2파티', '1파티 2파티'],
    ['1이랑 2파티', '1파티 2파티'],
    ['1하고 2파티', '1파티 2파티'],
    ['1 그리고 2파티', '1파티 2파티'],
    ['1~3파티', '1파티 2파티 3파티'],
    ['1파티 2파티', '1파티 2파티'],
    ['전원1파티', '전원 1파티'],
    ['3파 중앙', '3파티 중앙'],
    ['3파는 중앙', '3파티는 중앙'],
    ['서일파티', '서일파티'], // 한글 단어 안의 숫자 말은 그대로
    ['일이파티', '1파티 2파티'], // 붙여 쓴 한 글자 숫자 말은 오름차순일 때만 나열로 읽는다 (파서는 후보로 낮춘다)
    ['삼사오파티', '3파티 4파티 5파티'],
    ['이이파티', '이이파티'], // 오름차순이 아니면 손대지 않는다
    ['３파티', '3파티'],
    ['중앙으로,  모여!!', '중앙으로 모여'],
    ['  공백   정리 ', '공백 정리'],
    ['', ''],
  ];
  for (const [input, out] of cases) {
    it(`${JSON.stringify(input)} -> ${JSON.stringify(out)}`, () => {
      expect(normalize(input)).toBe(out);
    });
  }

  it('멱등', () => {
    for (const [, out] of cases) expect(normalize(out)).toBe(out);
  });
});
